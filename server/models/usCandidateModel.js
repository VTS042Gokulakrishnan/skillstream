const mongoose = require("mongoose");
const schema = mongoose.Schema;
const userSchema = new schema(
  {
    googleId: String,
    userId: String,
    email: String,
    name: String,
    password: String,
    role: String,
    securityCode: String,
    isEmailVerified: Boolean,
    phone_number: String,
    website: String,
    currentSalary: String,
    expectedSalary: String,
    experience: String,
    work_experience: Array,
    Education: Array,
    awards: Array,
    age: String,
    educationLevels: String,
    language: Array,
    position: String,
    jobTitle: String,
    allowInSearch: String,
    description: String,
    image: String,
    social: {
      facebook: String,
      twitter: String,
      linkedIn: String,
      googlePlus: String,
    },
    country: String,
    state: String,
    city: String,
    address: String,
    skills: Array,
    gender: String,
    shortlistedJobs: Array,
    resume: String,
    jobAlerts: Array,
    appliedJobs: Array,
    notifications: Array,
    profileCompleted: Boolean,
    isResumeUploaded: Boolean,
    profileViews: [],
    messages: [],
    practiceInterview: Array,
    practiceInterviewCount: Number,
  },
  { timestamps: true }
);

module.exports = mongoose.model("US-Candidate", userSchema);
